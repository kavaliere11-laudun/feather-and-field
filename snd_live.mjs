import { createRequire } from 'module';
const require = createRequire('/opt/npm-tools/node_modules/');
const { chromium } = require('playwright');
const browser = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] }); const errors = [];
const page = await (await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, deviceScaleFactor: 2 })).newPage();
page.on('pageerror', e => errors.push(e.message));
await page.goto(process.env.URL); await page.waitForTimeout(1000);
await page.locator('#sheetClose').click();
await page.evaluate(() => window.__ffDebug.rich()); await page.waitForTimeout(400);
if (await page.locator('#sheet').isVisible()) await page.locator('#sheetClose').click();
await page.touchscreen.tap(200, 500); await page.waitForTimeout(300);
console.log('running', await page.evaluate(() => window.__ffDebug.snd.running));
const p = await page.evaluate(() => window.__ffDebug.pond());
await page.evaluate(([x, y]) => window.__ffDebug.zoomTo(x, y, .6), p);
await page.waitForTimeout(8000);
await page.locator('#gear').click(); await page.waitForTimeout(600);
await page.screenshot({ path: 'r/snd/settings.png' });
await page.locator('.seg').nth(1).locator('button').nth(1).click(); await page.waitForTimeout(300);
console.log('prefs', JSON.stringify(await page.evaluate(() => window.__ffDebug.snd.prefs)), await page.evaluate(() => localStorage.getItem('ff_audio')));
await page.waitForTimeout(3000);
await browser.close(); console.log(errors.length ? errors.join('\n') : 'no errors');
