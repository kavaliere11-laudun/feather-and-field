// Phone walkthrough of the new screens. Usage: URL=... node shot_ui2.mjs OUTPREFIX
import { createRequire } from 'module';
const require = createRequire('/opt/npm-tools/node_modules/');
const { chromium } = require('playwright');
const out = process.argv[2] || 'r/u2';
const browser = await chromium.launch();
const errors = [];
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true });
const page = await ctx.newPage();
page.on('pageerror', e => errors.push(e.message));
await page.goto(process.env.URL);
await page.waitForTimeout(1200);
await page.locator('#sheetClose').click();
await page.evaluate(() => window.__ffDebug.rich());
await page.waitForTimeout(500);
if (await page.locator('#sheet').isVisible()) await page.locator('#sheetClose').click();
await page.evaluate(() => window.__ffDebug.grades(true));
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}_grades.png` });
const shot = async (name, fn) => { await fn(); await page.waitForTimeout(700); await page.screenshot({ path: `${out}_${name}.png` }); };
await shot('flock', () => page.locator('#flockBtn').click());
await page.locator('#sheetClose').click();
const pts = await page.evaluate(() => window.__ffDebug.points());
await shot('coop', () => page.touchscreen.tap(...pts.coop0));
await page.locator('#sheetBody').evaluate(el => el.scrollTop = 600); await page.waitForTimeout(200); await page.screenshot({ path: `${out}_coop2.png` });
await page.locator('#sheetClose').click();
await shot('feed', async () => { await page.locator('#tabbar button[data-tab="market"]').click(); await page.waitForTimeout(300); await page.locator('.seg button').nth(1).click(); });
await shot('build', () => page.locator('.seg button').nth(2).click());
await shot('breeds', () => page.locator('.seg button').nth(3).click());
await page.locator('#sheetBody').evaluate(el => el.scrollTop = 900); await page.waitForTimeout(300); await page.screenshot({ path: `${out}_breeds2.png` });
await page.locator('#sheetClose').click();
await shot('awards', () => page.locator('#lvlPill').click());
await page.locator('#sheetClose').click();
const p2 = await page.evaluate(() => window.__ffDebug.points());
await shot('bird', () => page.touchscreen.tap(...p2.bird));
await page.locator('#sheetBody').evaluate(el => el.scrollTop = 2000); await page.waitForTimeout(200); await page.screenshot({ path: `${out}_bird2.png` });
await page.locator('#sheetClose').click();
await page.evaluate(() => { window.__ffDebug.scroll(1); });
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}_bottom.png` });
await browser.close();
console.log(errors.length ? errors.join('\n') : 'no errors');
